-- =====================================================================
-- V1 - Schema inicial do MVP (repeticao espacada para simulados AWS)
-- Fonte de verdade do banco. Hibernate roda com ddl-auto=validate.
-- =====================================================================

CREATE TABLE user_account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(180) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(120) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_account_email UNIQUE (email)
);

CREATE TABLE exam_source (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES user_account (id) ON DELETE CASCADE,
    name          VARCHAR(200) NOT NULL,
    provider      VARCHAR(60)  NOT NULL DEFAULT 'UDEMY',
    raw_text_hash CHAR(64)     NOT NULL,
    imported_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_exam_source_hash UNIQUE (raw_text_hash)
);

CREATE TABLE question (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_source_id BIGINT      NOT NULL REFERENCES exam_source (id) ON DELETE CASCADE,
    topic          VARCHAR(120),
    stem           TEXT        NOT NULL,
    explanation    TEXT,
    multi_select   BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE answer_option (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT   NOT NULL REFERENCES question (id) ON DELETE CASCADE,
    position    SMALLINT NOT NULL,
    text        TEXT     NOT NULL,
    is_correct  BOOLEAN  NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_answer_option_position UNIQUE (question_id, position)
);

-- Um card por (usuario, questao): o agendamento e individual.
CREATE TABLE review_card (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES user_account (id) ON DELETE CASCADE,
    question_id      BIGINT       NOT NULL REFERENCES question (id) ON DELETE CASCADE,
    ease_factor      NUMERIC(4,2) NOT NULL DEFAULT 2.50,
    interval_days    INTEGER      NOT NULL DEFAULT 0,
    repetitions      INTEGER      NOT NULL DEFAULT 0,
    due_date         DATE         NOT NULL,
    last_reviewed_at TIMESTAMPTZ,
    CONSTRAINT uk_review_card_user_question UNIQUE (user_id, question_id),
    CONSTRAINT ck_review_card_ef          CHECK (ease_factor >= 1.30),
    CONSTRAINT ck_review_card_interval    CHECK (interval_days >= 0),
    CONSTRAINT ck_review_card_repetitions CHECK (repetitions >= 0)
);

CREATE TABLE review_attempt (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id     BIGINT      NOT NULL REFERENCES review_card (id) ON DELETE CASCADE,
    quality     SMALLINT    NOT NULL,
    is_correct  BOOLEAN     NOT NULL,
    duration_ms INTEGER,
    answered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_review_attempt_quality CHECK (quality BETWEEN 0 AND 5),
    CONSTRAINT ck_review_attempt_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
);

-- Indice que sustenta a fila do dia (endpoint mais critico em leitura).
CREATE INDEX idx_review_card_due ON review_card (user_id, due_date);
CREATE INDEX idx_question_source ON question (exam_source_id);
CREATE INDEX idx_review_attempt_card ON review_attempt (card_id, answered_at);
